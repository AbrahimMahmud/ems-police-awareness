def simulate_outcome(r_):
    """One draw of the SIMULATED outcome on the whole skeleton. Returns (N, T)."""
    innov = r_.normal(0, SIGMA * np.sqrt(max(1 - RHO ** 2, 0.0)), (N, T))
    e = np.empty((N, T))
    e[:, 0] = r_.normal(0, SIGMA, N)
    for t in range(1, T):
        e[:, t] = RHO * e[:, t - 1] + innov[:, t]
    day_shock = r_.normal(0, DAY_SD, T)
    return (MU + CD_EFFECT[:, None] + DOW_EFFECT[DOW_OF_DATE][None, :]
            + day_shock[None, :] + BETA * X_OF_DATE[None, :] + e)


