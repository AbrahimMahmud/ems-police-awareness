# ---------------------------------------------------------------------------
# SELF-CHECKS. Each is a pure function of the two output frames, returning
# (ok, detail). Each is then re-run against a mutated copy and REQUIRED TO FAIL.
#
# The prior defect this apparatus exists for: a check named
# `outputs_labelled_simulated` wrote 'data' as a ROW LABEL in a `parameter`
# column and then asked `if 'data' not in t.columns`. That condition was true of
# every possible output, so the check reported problems on correct output and
# exited 1 unconditionally. It had never passed and could not. Its mirror image
# — a check that cannot fail — is §7.5's subject. Running both directions on
# every invocation is the only way to know which kind you have.
# ---------------------------------------------------------------------------
def check_label_present(main, par):
    """Every row of every artifact carries data = SIMULATED, as a COLUMN."""
    for name, t in (("main", main), ("params", par)):
        if LABEL_COL not in t.columns:
            return False, f"{name} has no '{LABEL_COL}' column"
        if len(t) == 0:
            return False, f"{name} is empty"
        bad = (t[LABEL_COL] != SIM_LABEL).sum()
        if bad:
            return False, f"{name} has {bad} row(s) not labelled {SIM_LABEL}"
    return True, f"{len(main)} + {len(par)} rows labelled {SIM_LABEL}"


def check_arms_distinct(main, par):
    """fixed_scale and within_window_z must not coincide anywhere."""
    f = main[main["arm"] == "fixed_scale"].set_index("sample_id")["coef_mean"]
    z = main[main["arm"] == "within_window_z"].set_index("sample_id")["coef_mean"]
    common = f.index.intersection(z.index)
    if len(common) == 0:
        return False, "no sample has both arms"
    rel = (z[common] - f[common]).abs() / f[common].abs().clip(lower=1e-30)
    bad = rel[rel <= DISTINCT_RTOL]
    if len(bad):
        return False, (f"{len(bad)} sample(s) where the two arms coincide within "
                       f"{DISTINCT_RTOL:.0%}: {list(bad.index)[:3]}")
    return True, f"{len(common)} samples, min relative gap {rel.min():.3f}"


def check_centre_arm_identical(main, par):
    """Centring is absorbed by the fixed effects: the centred arm MUST equal
    the fixed arm. This is the claim; if it stops holding, the decomposition
    into "centring is harmless, dividing is not" is wrong."""
    c = main[main["arm"] == "within_window_centred"]
    if len(c) == 0:
        return False, "the centred arm was never fitted"
    rel = ((c["coef_mean"] - c["identity_predicted_coef"]).abs()
           / c["identity_predicted_coef"].abs().clip(lower=1e-30))
    bad = rel[rel > CENTRE_RTOL]
    if len(bad):
        return False, (f"{len(bad)} sample(s) where centring changed the coefficient: "
                       f"max relative difference {rel.max():.3e}")
    return True, f"{len(c)} samples, max relative difference {rel.max():.3e}"


def check_identity_holds(main, par):
    """b_z == b_fixed * s_W, exactly, on every fitted row."""
    z = main[(main["arm"] == "within_window_z") & (main["n_fits"] > 0)]
    if len(z) == 0:
        return False, "no fitted within_window_z rows"
    rel = (z["identity_abs_err"] / z["identity_predicted_coef"].abs().clip(lower=1e-30))
    bad = rel[rel > IDENTITY_RTOL]
    if len(bad):
        return False, (f"{len(bad)} row(s) violate b_z = b_fixed * s_W; "
                       f"worst relative error {rel.max():.3e}")
    return True, f"{len(z)} rows, worst relative error {rel.max():.3e}"


def check_planted_effect_recovered(main, par):
    """The fixed-scale arm must return the planted effect. If it does not, the
    simulation is miswired and nothing else in the file means anything."""
    f = main[(main["arm"] == "fixed_scale") & (main["n_fits"] > 0)]
    if len(f) == 0:
        return False, "no fitted fixed_scale rows"
    worst, worst_id = 0.0, None
    for _, row in f.iterrows():
        n = max(int(row["n_fits"]), 1)
        mc = (row["coef_sd_across_draws"] / np.sqrt(n) if n >= 5
              and np.isfinite(row["coef_sd_across_draws"]) else row["se_mean"])
        if not np.isfinite(mc) or mc <= 0:
            return False, f"{row['sample_id']}: no usable band"
        t = abs(row["coef_mean"] - row["beta_true"]) / mc
        if t > worst:
            worst, worst_id = t, row["sample_id"]
    if worst > 4.0:
        return False, (f"{worst_id}: fixed-scale mean is {worst:.1f} standard errors "
                       f"from beta_true")
    return True, f"worst departure {worst:.2f} SE (at {worst_id})"


def check_realised_days_reported(main, par):
    """The sweep's x-axis must be the quantity that varied. Nearest-episode
    assignment truncates long windows, so realised length is BELOW nominal and
    the gap grows with L. A table that reports only nominal L labels its axis
    with a number that is not what changed."""
    w = (main[main["block"] == "window_length"]
         .drop_duplicates("sample_id")
         .sort_values("nominal_half_window_days"))
    if len(w) < 2:
        return False, "fewer than two window-length samples"
    if (w["realised_days_per_episode_district"]
            > w["nominal_days_per_episode_district"] + 1e-9).any():
        return False, "a realised length exceeds its nominal length"
    longest = w.iloc[-1]
    if (longest["realised_days_per_episode_district"]
            >= longest["nominal_days_per_episode_district"] - 1e-9):
        return False, (f"realised == nominal at the longest window "
                       f"(L={int(longest['nominal_half_window_days'])}); either "
                       "truncation stopped happening or the nominal label is being "
                       "reported as if it were realised")
    r = w["realised_days_per_episode_district"].to_numpy()
    if not np.all(np.diff(r) > 0):
        return False, f"realised length is not increasing in L: {list(r)}"
    return True, (f"realised {[round(float(v), 2) for v in r]} against nominal "
                  f"{[int(v) for v in w['nominal_days_per_episode_district']]}")


def check_dates_inside_freeze(main, par):
    """No sample may reach outside the permitted window. select_sample already
    filtered the inputs; this proves the SAMPLES BUILT FROM THEM stayed inside,
    which is a different statement and the one the artifact asserts."""
    wins = [(pd.Timestamp(a), pd.Timestamp(b)) for a, b in active_windows()]
    lo = pd.to_datetime(main["sample_date_min"])
    hi = pd.to_datetime(main["sample_date_max"])
    inside = pd.Series(False, index=main.index)
    for a, b in wins:
        inside |= lo.between(a, b) & hi.between(a, b)
    if not inside.all():
        bad = main.loc[~inside, "sample_id"].tolist()[:3]
        return False, f"{int((~inside).sum())} sample(s) outside {wins}: {bad}"
    return True, f"all {len(main)} rows inside {[(str(a.date()), str(b.date())) for a, b in wins]}"


