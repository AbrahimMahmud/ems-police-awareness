def fit(st, xcol):
    """`y_sim ~ x | ep_cd + dow`, clustered on the date. Returns (coef, se)."""
    m = pf.feols(f"y_sim ~ {xcol} | ep_cd + dow", st, vcov={"CRV1": CLUSTER_VAR})
    return float(m.coef().loc[xcol]), float(m.se().loc[xcol])


